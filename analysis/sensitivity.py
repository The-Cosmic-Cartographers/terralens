"""Serial-correlation and sensitivity notes (NAS-47).

Computes the numbers that belong in the app's method box and in the project
page's limitations section, then writes them to docs/sensitivity-notes.md:

  * lag-1 autocorrelation and the Hamed-Rao variance factor, per row
  * raw seasonal MK p vs the corrected p, so the reader can see the cost of
    the correction rather than being told about it
  * the annual-mean MK p as the D22 sensitivity check
  * period sensitivity from the precomputed Time Machine windows
  * coverage and missing months, which decide whether a row is withheld

Usage:
    python -m analysis.sensitivity
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from analysis import stats as tl
from analysis import windows as tw
from analysis.run import (
    ANNUAL_AGG,
    BASELINE,
    PROCESSED,
    PRODUCT_TYPE,
    REPO_ROOT,
    load_series,
    to_rows,
)
from pipeline.registry import VARIABLES

DOC = REPO_ROOT / "docs" / "sensitivity-notes.md"
REGION_NAMES = {
    "ireland": "Ireland",
    "iberia": "Iberia",
    "sahel": "Sahel (West Africa)",
    "nw_south_asia": "NW South Asia (Rajasthan-Punjab)",
    "us_southwest": "US Southwest (Colorado Basin)",
}
VARIABLE_NAMES = {
    "t2m": "Air temperature (2 m)",
    "soil_moisture_0_10": "Soil moisture (0-10 cm)",
    "evapotranspiration": "Evapotranspiration",
    "precipitation": "Precipitation",
    "aerosol": "Aerosol optical depth",
    "no2": "NO2 column (troposphere)",
}
UNIT_PER_DECADE = {
    "t2m": "°C/decade",
    "soil_moisture_0_10": "kg/m²/decade",
    "evapotranspiration": "mm/day/decade",
    "precipitation": "mm/month/decade",
    "aerosol": "AOT/decade",
    "no2": "molec/cm²/decade",
}


def analyse(parquet: Path, region: str) -> dict:
    frame, meta = load_series(parquet)
    variable_id = meta["variable_id"]
    spec = VARIABLES[variable_id]
    rows = to_rows(frame)

    result = tl.analyze_series(
        rows,
        dataset_id=meta["dataset_id"],
        variable_id=variable_id,
        region_id=region,
        unit=meta["unit"],
        product_type=PRODUCT_TYPE.get(variable_id, "reanalysis"),
        window=(spec.start_year, spec.end_year),
        baseline=BASELINE,
        annual_agg=ANNUAL_AGG.get(variable_id, "mean"),
        with_pettitt=True,
        with_seasonal_strip=True,
    )

    windows = tw.windows_for_series(
        rows,
        variable_id=variable_id,
        region_id=region,
        window=(spec.start_year, spec.end_year),
        baseline=BASELINE,
        annual_agg=ANNUAL_AGG.get(variable_id, "mean"),
        min_window_years=10,
    )
    slopes = [w["sen_slope_per_year"] for w in windows if w["sen_slope_per_year"] is not None]
    significant = [w for w in windows if w["p_value"] is not None and w["p_value"] < 0.05]

    return {
        "region": region,
        "variable_id": variable_id,
        "unit": UNIT_PER_DECADE.get(variable_id, f"{meta['unit']}/decade"),
        "row": result,
        "debug": result.get("_debug", {}),
        "change_point": result.get("change_point"),
        "windows": len(windows),
        "windows_significant": len(significant),
        "slope_min": min(slopes) if slopes else None,
        "slope_max": max(slopes) if slopes else None,
    }


def _fmt_p(value: float | None) -> str:
    if value is None:
        return "—"
    if value <= 0:
        return "<1e-300"
    if value < 1e-4:
        return f"{value:.1e}"
    return f"{value:.4f}"


def _fmt(value: float | None, digits: int = 3) -> str:
    if value is None:
        return "—"
    return f"{value:+.{digits}f}"


def build_document(rows: list[dict]) -> str:
    lines: list[str] = []
    lines.append("# Serial correlation and sensitivity notes")
    lines.append("")
    lines.append(
        "Generated by `python -m analysis.sensitivity` from the processed series. "
        "Every number below comes from the same code path that writes `data/results/`, "
        "so this page cannot drift from the app."
    )
    lines.append("")
    lines.append("## Method-box text (app)")
    lines.append("")
    lines.append(
        "> **How the trend is measured.** Each month is compared with its 1991–2020 "
        "normal for that calendar month, and the seasonal Mann–Kendall test asks whether "
        "the resulting anomalies rise or fall consistently through the record. "
        "Because consecutive months are not independent, the test's variance is "
        "corrected with the Hamed–Rao method using the lag-1 autocorrelation of the "
        "residuals; without it, a slow-moving series would look more certain than it is. "
        "The slope is Sen's slope — the median of all pairwise slopes — reported per "
        "decade with a 95% confidence interval."
    )
    lines.append(">")
    lines.append(
        "> **What we check.** The same test on annual means is shown as a sensitivity "
        "check: if the monthly and annual results disagree, the row is fragile and we say "
        "so. Every verdict uses the Benjamini–Hochberg adjusted p-value for its family "
        "(a region's five rows, or one variable across regions), so the chance of a false "
        "positive does not grow with the number of rows on screen."
    )
    lines.append(">")
    lines.append(
        "> **What a verdict means.** *Significant trend* means the adjusted p-value is "
        "below 0.05. *Weak evidence* is 0.05–0.10 and is not a claim. *No clear trend* "
        "means the record cannot show one — not that nothing changed. *Not enough data* "
        "means the coverage rules failed before any test ran, and no slope or p-value is "
        "reported at all."
    )
    lines.append("")

    lines.append("## Per row")
    lines.append("")
    lines.append(
        "| Region | Variable | Months | lag-1 ρ | Hamed–Rao factor | raw p | adjusted p "
        "| annual-mean p | verdict | slope | 95% CI |"
    )
    lines.append("| -- | -- | -- | -- | -- | -- | -- | -- | -- | -- | -- |")
    for item in rows:
        row = item["row"]
        dbg = item["debug"]
        if row["verdict"] == "not_enough_data":
            lines.append(
                f"| {REGION_NAMES.get(item['region'], item['region'])} "
                f"| {VARIABLE_NAMES.get(item['variable_id'], item['variable_id'])} "
                f"| {row['observation_count']} | — | — | — | — | — "
                f"| Not enough data | — | — |"
            )
            continue
        slope = row["sen_slope_per_year"]
        low, high = row["confidence_interval_95"]
        lines.append(
            f"| {REGION_NAMES.get(item['region'], item['region'])} "
            f"| {VARIABLE_NAMES.get(item['variable_id'], item['variable_id'])} "
            f"| {row['observation_count']} "
            f"| {_fmt(dbg.get('lag1_rho'), 2)} "
            f"| {dbg.get('hamed_rao_factor', float('nan')):.2f} "
            f"| {_fmt_p(dbg.get('seasonal_mk_raw_p'))} "
            f"| {_fmt_p(row['adjusted_p_value'])} "
            f"| {_fmt_p(dbg.get('annual_mk_p'))} "
            f"| {tl.VERDICT_LABEL[row['verdict']]} "
            f"| {_fmt(slope * 10 if slope is not None else None, 2)} {item['unit']} "
            f"| {_fmt(low * 10 if low is not None else None, 2)} to "
            f"{_fmt(high * 10 if high is not None else None, 2)} |"
        )
    lines.append("")

    lines.append("## Period sensitivity")
    lines.append("")
    lines.append(
        "Each row recomputed for every start/end pair at least 10 years apart. "
        "The spread is the honest width of the answer: a slope quoted from one window "
        "is one window's slope."
    )
    lines.append("")
    lines.append("| Region | Variable | Windows | Significant (<0.05) | Slope range |")
    lines.append("| -- | -- | -- | -- | -- |")
    for item in rows:
        if not item["windows"]:
            continue
        share = 100 * item["windows_significant"] / item["windows"]
        lines.append(
            f"| {REGION_NAMES.get(item['region'], item['region'])} "
            f"| {VARIABLE_NAMES.get(item['variable_id'], item['variable_id'])} "
            f"| {item['windows']} | {item['windows_significant']} ({share:.0f}%) "
            f"| {_fmt(item['slope_min'] * 10 if item['slope_min'] is not None else None, 2)} to "
            f"{_fmt(item['slope_max'] * 10 if item['slope_max'] is not None else None, 2)} "
            f"{item['unit']} |"
        )
    lines.append("")

    lines.append("## Coverage and withholding")
    lines.append("")
    lines.append(
        "A month is treated as missing when its `coverage_fraction` is below 0.5; a row is "
        "withheld entirely below 10 complete years or above 20% missing months. Withheld "
        "rows carry `withheld_reason` and no statistics."
    )
    lines.append("")
    lines.append("| Region | Variable | Observed months | Missing months | Mean coverage | State |")
    lines.append("| -- | -- | -- | -- | -- | -- |")
    for item in rows:
        row = item["row"]
        state = f"withheld: {row['withheld_reason']}" if row["withheld_reason"] else "tested"
        lines.append(
            f"| {REGION_NAMES.get(item['region'], item['region'])} "
            f"| {VARIABLE_NAMES.get(item['variable_id'], item['variable_id'])} "
            f"| {row['observation_count']} | {row['missing_month_count']} "
            f"| {row['mean_coverage_fraction']:.3f} | {state} |"
        )
    lines.append("")

    lines.append("## Limitations worth stating out loud")
    lines.append("")
    lines.append(
        "* **Reanalysis is not observation.** MERRA-2 and GLDAS are model-plus-assimilation "
        "products; a trend in them is a trend in the assimilated system, not a thermometer."
    )
    lines.append(
        "* **The p-value depends on the window.** The period table above exists because a "
        "verdict can change with the start and end years, and pretending otherwise would "
        "be the single easiest way to mislead a reader."
    )
    lines.append(
        '* **"No clear trend" is not "no change".** With 21–45 years and this much '
        "year-to-year noise, many real changes are simply not detectable yet; the "
        "detectability figure says how long a record would be needed."
    )
    lines.append(
        "* **One change point at most.** Pettitt finds a single level shift and is "
        "conservative on short records; it is a diagnostic, never a verdict."
    )
    lines.append(
        "* **No attribution.** Nothing here says why a trend exists, and no result should "
        "be worded as if it did."
    )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parquets = sorted(PROCESSED.glob("*/*.parquet"))
    if not parquets:
        print("no processed series found")
        return 1

    rows = [analyse(path, path.stem) for path in parquets]
    rows.sort(key=lambda item: (item["region"], item["variable_id"]))
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(build_document(rows), encoding="utf-8")
    print(f"wrote {DOC.relative_to(REPO_ROOT)} ({len(rows)} rows)")
    for item in rows:
        row = item["row"]
        print(
            f"  {item['region']:14s} {item['variable_id']:8s} "
            f"{tl.VERDICT_LABEL[row['verdict']]:16s} "
            f"windows={item['windows']:4d} significant={item['windows_significant']:4d}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


